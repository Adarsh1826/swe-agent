import { githubapp } from "../../auth/auth.js";
import { LLMFix } from "../../rag/llmcaller.js";



export async function createPR(
  repoUrl: string,
  installationId: number,
  fix: LLMFix,
  issueNumber: number
): Promise<string> {
  // get authenticated octokit for this installation
  const octokit = await githubapp.getInstallationOctokit(installationId);

  // extract owner and repo from repoUrl
  const parts = repoUrl.replace("https://github.com/", "").split("/");
  const owner = parts[0];
  const repo = parts[1];

  // get the default branch SHA
  const { data: refData } = await octokit.rest.git.getRef({
    owner,
    repo,
    ref: "heads/main",
  });

  const baseSHA = refData.object.sha;

  // create a new branch
  const branchName = `swe-agent-fix-${issueNumber}`;

  await octokit.rest.git.createRef({
    owner,
    repo,
    ref: `refs/heads/${branchName}`,
    sha: baseSHA,
  });

  console.log(`✅ Branch created: ${branchName}`);

  // check if file exists or not — handles both create and update
  let fileSHA: string | undefined;

  try {
    const { data: fileData } = await octokit.rest.repos.getContent({
      owner,
      repo,
      path: fix.filePath,
      ref: branchName,
    });
    fileSHA = (fileData as any).sha;
    console.log(`📝 Updating existing file: ${fix.filePath}`);
  } catch (err) {
    // file doesn't exist — will create it
    fileSHA = undefined;
    console.log(`🆕 Creating new file: ${fix.filePath}`);
  }

  // create or update file on the branch
  await octokit.rest.repos.createOrUpdateFileContents({
    owner,
    repo,
    path: fix.filePath,
    message: `fix: resolve issue #${issueNumber}`,
    content: Buffer.from(fix.fixedCode).toString("base64"),
    ...(fileSHA && { sha: fileSHA }), // only pass sha if file exists
    branch: branchName,
  });

  console.log(`✅ Fix committed to branch: ${branchName}`);

  // open the pull request
  const { data: pr } = await octokit.rest.pulls.create({
    owner,
    repo,
    title: `fix: resolve issue #${issueNumber}`,
    body: `This PR was auto-generated by SWE Agent to fix issue #${issueNumber}.`,
    head: branchName,
    base: "main",
  });

  console.log(`✅ PR created: ${pr.html_url}`);

  return pr.html_url;
}